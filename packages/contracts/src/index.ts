/** Frozen R1-A public contracts. Changes require controller review. */
export const SCHEMA_VERSION = 'phone-workbench/0.1-r1a' as const;
export type SourceKind = 'NONE' | 'REAL_DEVICE' | 'SIMULATED' | 'FIXTURE';
export type DiscoveryStatus = 'ready' | 'not_configured' | 'unavailable' | 'error';
export type ConnectionState = 'connected' | 'unauthorized' | 'offline' | 'disconnected' | 'unknown';
export type CapabilityState = 'supported' | 'unsupported' | 'unknown' | 'permission_required';
export type ErrorCode = 'INVALID_ARGUMENT' | 'ADAPTER_NOT_CONFIGURED' | 'ADAPTER_UNAVAILABLE' |
  'DISCOVERY_FAILED' | 'TIMEOUT' | 'CANCELLED' | 'CAPABILITY_UNSUPPORTED' |
  'STALE_OBSERVATION' | 'TARGET_MISMATCH' | 'EFFECT_UNKNOWN' | 'INTERNAL_ERROR' | 'CORE_CLOSED';

export interface DomainError {
  code: ErrorCode;
  reasonCode: string;
  message: string;
  retryPolicy: 'never' | 'after_refresh' | 'reconcile_first';
}
export interface Capability {
  operation: string;
  state: CapabilityState;
  reasonCode: string;
  scope: 'device' | 'display' | 'application';
  evidence: 'NOT_RUN' | 'STATIC_REVIEW' | 'SIMULATED_PASS' | 'DEVICE_PASS';
}

/** Internal adapter facts only. adapterDeviceKey is opaque; never an ADB serial. */
export interface AdapterDevice {
  adapterDeviceKey: string;
  label: string;
  state: 'connected' | 'unauthorized' | 'offline';
  capabilities: Capability[];
}
/** Non-ready discoveries cannot prove an empty or disconnected device list. */
export type DeviceDiscovery =
  | {status:'ready'; sourceKind:Exclude<SourceKind,'NONE'>; observedAt:string; devices:AdapterDevice[]}
  | {status:'not_configured'|'unavailable'|'error'; sourceKind:SourceKind; observedAt:string; devices:[]; error:DomainError};
export interface DeviceAdapter {
  readonly adapterId: string;
  discover(options?: {signal?:AbortSignal}): Promise<DeviceDiscovery>;
  dispose(): Promise<void>;
}

/** Generated by CoreService, never by the adapter or UI. */
export interface DeviceRecord {
  deviceId: string;
  label: string;
  connectionState: ConnectionState;
  connectionGeneration: number;
  stale: boolean;
  lastSeenAt: string;
  capabilities: Capability[];
}
export interface WorkspaceSnapshot {
  schemaVersion: typeof SCHEMA_VERSION;
  runtimeId: string;
  revision: number;
  sourceKind: SourceKind;
  discoveryStatus: DiscoveryStatus;
  observedAt: string;
  lastSuccessfulDiscoveryAt: string | null;
  devices: DeviceRecord[];
  controlOwner: 'none' | 'human' | 'agent' | 'transitioning';
  /** R1-A has no active interaction session; later schemas will extend it. */
  activeSession: null;
  error: DomainError | null;
}
export interface CoreService {
  getSnapshot(): Promise<WorkspaceSnapshot>;
  refreshDevices(): Promise<WorkspaceSnapshot>;
  dispose(): Promise<void>;
}
export interface CoreServiceOptions {
  adapter?: DeviceAdapter;
  now?: () => string;
  idFactory?: () => string;
}
export interface CoreClosedError extends Error { code: 'CORE_CLOSED'; }

/** Reserved status vocabulary, not a claim that command execution exists in R1-A. */
export type CommandProgress =
  | {state:'pending'; phase:'queued'|'running'|'verifying'; terminalOutcome?:never}
  | {state:'terminal'; terminalOutcome:'verified_success'|'executed_unverified'|'rejected'|'failed'|'cancelled'|'effect_unknown'};

/** Renderer bridge: fixed methods, no generic IPC or filesystem access. */
export interface DesktopBridge {
  getSnapshot(): Promise<WorkspaceSnapshot>;
  getMode(): Promise<'unconfigured'|'demo'>;
  setDemoScenario(scenario: DemoScenario): Promise<WorkspaceSnapshot>;
}
export const DEMO_SCENARIOS = ['empty','unauthorized','offline','busy','effect_unknown','virtual_unavailable'] as const;
export type DemoScenario = typeof DEMO_SCENARIOS[number];
